"""
Autonomous Development Requests Router
Provides endpoints for viewing and managing development requests generated by AI agents
"""

from fastapi import APIRouter, HTTPException, Request
from fastapi.responses import JSONResponse, HTMLResponse
from fastapi.templating import Jinja2Templates
import logging
from typing import List, Dict, Any
from ..utils.autonomous_communication import communication_hub

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/autonomous", tags=["autonomous-development"])
templates = Jinja2Templates(directory="cmp/templates")

@router.get("/requests", response_class=HTMLResponse)
async def autonomous_dev_requests_page(request: Request):
    """Dashboard page for viewing autonomous development requests"""
    return templates.TemplateResponse(
        request,
        "autonomous_dev_requests.html",
        {
            "request": request,
        }
    )

@router.get("/development-requests")
async def get_development_requests():
    """Get all pending development requests from AI agents"""
    try:
        pending_requests = await communication_hub.get_pending_requests()
        
        # Sort by priority and timestamp
        priority_order = {"critical": 0, "high": 1, "medium": 2, "low": 3}
        pending_requests.sort(key=lambda x: (
            priority_order.get(x.get("priority", "low"), 3),
            x.get("timestamp", "")
        ))
        
        return {
            "success": True,
            "total_requests": len(pending_requests),
            "requests": pending_requests,
            "summary": {
                "critical": len([r for r in pending_requests if r.get("priority") == "critical"]),
                "high": len([r for r in pending_requests if r.get("priority") == "high"]),
                "medium": len([r for r in pending_requests if r.get("priority") == "medium"]),
                "low": len([r for r in pending_requests if r.get("priority") == "low"]),
            }
        }
        
    except Exception as e:
        logger.error(f"Error getting development requests: {e}")
        raise HTTPException(status_code=500, detail=str(e))

@router.post("/development-requests/{request_id}/complete")
async def mark_request_completed(request_id: str):
    """Mark a development request as completed"""
    try:
        success = await communication_hub.mark_request_completed(request_id)
        
        if success:
            return {
                "success": True,
                "message": f"Request {request_id} marked as completed"
            }
        else:
            raise HTTPException(status_code=404, detail="Request not found")
            
    except Exception as e:
        logger.error(f"Error marking request completed: {e}")
        raise HTTPException(status_code=500, detail=str(e))

@router.get("/system-health")
async def get_autonomous_system_health():
    """Get health status of the autonomous development system"""
    try:
        from ..agents.lead_developer import lead_developer
        
        # Run quick health check
        assessment = await lead_developer.autonomous_self_assessment()
        
        return {
            "success": True,
            "system_health": assessment["system_health"],
            "last_assessment": assessment["timestamp"],
            "improvement_opportunities": len(assessment.get("improvement_opportunities", [])),
            "autonomous_status": "active"
        }
        
    except Exception as e:
        logger.error(f"Error getting system health: {e}")
        return {
            "success": False,
            "error": str(e),
            "autonomous_status": "error"
        }